-- Manos Solidarias: esquema académico en español.
-- Ejecutar completo en Supabase > SQL Editor.
-- No elimina ni modifica las tablas antiguas (profiles, foundations, donations).

create table if not exists public.perfiles (
    id uuid primary key references auth.users(id) on delete cascade,
    correo text not null,
    nombre text not null default '',
    apellido_paterno text not null default '',
    apellido_materno text not null default '',
    telefono text not null default '',
    rol text not null default 'DONANTE' check (rol in ('DONANTE', 'FUNDACION')),
    fecha_registro timestamptz not null default now()
);

create table if not exists public.fundaciones (
    id bigint generated by default as identity primary key,
    usuario_id uuid unique references auth.users(id) on delete cascade,
    nombre text not null,
    descripcion text not null default '',
    direccion text not null default '',
    ciudad text not null default '',
    telefono text not null default '',
    correo text not null default '',
    fecha_registro timestamptz not null default now()
);

create table if not exists public.necesidades (
    id bigint generated by default as identity primary key,
    fundacion_id bigint not null references public.fundaciones(id) on delete cascade,
    categoria text not null,
    descripcion text not null,
    cantidad numeric not null check (cantidad > 0),
    unidad text not null,
    urgencia text not null default 'MEDIA' check (urgencia in ('ALTA', 'MEDIA', 'BAJA')),
    estado text not null default 'ACTIVA' check (estado in ('ACTIVA', 'CUBIERTA')),
    fecha_publicacion timestamptz not null default now()
);

create table if not exists public.donaciones (
    id bigint generated by default as identity primary key,
    donante_id uuid not null references auth.users(id) on delete cascade,
    fundacion_id bigint not null references public.fundaciones(id) on delete restrict,
    necesidad_id bigint references public.necesidades(id) on delete set null,
    tipo_objeto text not null,
    categoria text not null,
    descripcion text not null default '',
    cantidad numeric not null check (cantidad > 0),
    unidad text not null,
    condicion text not null,
    tipo_entrega text not null,
    puntaje_ia numeric,
    estado text not null default 'BORRADOR'
        check (estado in ('BORRADOR', 'ENVIADA', 'EN_REVISION', 'ACEPTADA', 'RECHAZADA')),
    fecha_registro timestamptz not null default now()
);

create table if not exists public.fotos_donacion (
    id bigint generated by default as identity primary key,
    donacion_id bigint not null references public.donaciones(id) on delete cascade,
    url_foto text not null,
    tipo_foto text not null check (tipo_foto in ('FRONTAL', 'TRASERA', 'DETALLE', 'EXTRA'))
);

create index if not exists idx_necesidades_estado_categoria
    on public.necesidades (estado, categoria);
create index if not exists idx_necesidades_fundacion
    on public.necesidades (fundacion_id);
create index if not exists idx_donaciones_donante
    on public.donaciones (donante_id);
create index if not exists idx_donaciones_fundacion
    on public.donaciones (fundacion_id);

-- Crea automáticamente el perfil y, si corresponde, la fundación usando
-- los datos enviados por la pantalla de registro de la aplicación.
create or replace function public.crear_datos_usuario()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
    rol_nuevo text;
begin
    rol_nuevo := upper(coalesce(new.raw_user_meta_data ->> 'rol', 'DONANTE'));
    if rol_nuevo not in ('DONANTE', 'FUNDACION') then
        rol_nuevo := 'DONANTE';
    end if;

    insert into public.perfiles (
        id, correo, nombre, apellido_paterno, apellido_materno, telefono, rol
    ) values (
        new.id,
        coalesce(new.email, ''),
        coalesce(new.raw_user_meta_data ->> 'nombre', ''),
        coalesce(new.raw_user_meta_data ->> 'apellido_paterno', ''),
        coalesce(new.raw_user_meta_data ->> 'apellido_materno', ''),
        coalesce(new.raw_user_meta_data ->> 'telefono', ''),
        rol_nuevo
    ) on conflict (id) do update set
        correo = excluded.correo,
        nombre = excluded.nombre,
        apellido_paterno = excluded.apellido_paterno,
        apellido_materno = excluded.apellido_materno,
        telefono = excluded.telefono,
        rol = excluded.rol;

    if rol_nuevo = 'FUNDACION' then
        insert into public.fundaciones (
            usuario_id, nombre, descripcion, direccion, ciudad, telefono, correo
        ) values (
            new.id,
            coalesce(nullif(new.raw_user_meta_data ->> 'nombre_fundacion', ''), 'Fundación sin nombre'),
            coalesce(new.raw_user_meta_data ->> 'descripcion_fundacion', ''),
            coalesce(new.raw_user_meta_data ->> 'direccion_fundacion', ''),
            coalesce(new.raw_user_meta_data ->> 'ciudad', ''),
            coalesce(new.raw_user_meta_data ->> 'telefono', ''),
            coalesce(new.email, '')
        ) on conflict (usuario_id) do update set
            nombre = excluded.nombre,
            descripcion = excluded.descripcion,
            direccion = excluded.direccion,
            ciudad = excluded.ciudad,
            telefono = excluded.telefono,
            correo = excluded.correo;
    end if;

    return new;
end;
$$;

drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario
after insert or update of raw_user_meta_data, email on auth.users
for each row execute function public.crear_datos_usuario();

-- Recupera cuentas ya creadas antes de instalar este esquema.
insert into public.perfiles (id, correo, nombre, apellido_paterno, apellido_materno, telefono, rol)
select
    id,
    coalesce(email, ''),
    coalesce(raw_user_meta_data ->> 'nombre', ''),
    coalesce(raw_user_meta_data ->> 'apellido_paterno', ''),
    coalesce(raw_user_meta_data ->> 'apellido_materno', ''),
    coalesce(raw_user_meta_data ->> 'telefono', ''),
    case when upper(coalesce(raw_user_meta_data ->> 'rol', 'DONANTE')) = 'FUNDACION'
        then 'FUNDACION' else 'DONANTE' end
from auth.users
on conflict (id) do nothing;

insert into public.fundaciones (usuario_id, nombre, descripcion, direccion, ciudad, telefono, correo)
select
    id,
    coalesce(nullif(raw_user_meta_data ->> 'nombre_fundacion', ''), 'Fundación sin nombre'),
    coalesce(raw_user_meta_data ->> 'descripcion_fundacion', ''),
    coalesce(raw_user_meta_data ->> 'direccion_fundacion', ''),
    coalesce(raw_user_meta_data ->> 'ciudad', ''),
    coalesce(raw_user_meta_data ->> 'telefono', ''),
    coalesce(email, '')
from auth.users
where upper(coalesce(raw_user_meta_data ->> 'rol', '')) = 'FUNDACION'
on conflict (usuario_id) do nothing;

alter table public.perfiles enable row level security;
alter table public.fundaciones enable row level security;
alter table public.necesidades enable row level security;
alter table public.donaciones enable row level security;
alter table public.fotos_donacion enable row level security;

drop policy if exists "perfil propio visible" on public.perfiles;
create policy "perfil propio visible" on public.perfiles for select to authenticated
using (id = auth.uid());
drop policy if exists "perfil propio editable" on public.perfiles;
create policy "perfil propio editable" on public.perfiles for update to authenticated
using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "fundaciones visibles" on public.fundaciones;
create policy "fundaciones visibles" on public.fundaciones for select to authenticated using (true);
drop policy if exists "fundacion propia insertable" on public.fundaciones;
create policy "fundacion propia insertable" on public.fundaciones for insert to authenticated
with check (usuario_id = auth.uid());
drop policy if exists "fundacion propia editable" on public.fundaciones;
create policy "fundacion propia editable" on public.fundaciones for update to authenticated
using (usuario_id = auth.uid()) with check (usuario_id = auth.uid());

drop policy if exists "necesidades visibles" on public.necesidades;
create policy "necesidades visibles" on public.necesidades for select to authenticated using (true);
drop policy if exists "necesidad propia insertable" on public.necesidades;
create policy "necesidad propia insertable" on public.necesidades for insert to authenticated
with check (exists (
    select 1 from public.fundaciones f
    where f.id = fundacion_id and f.usuario_id = auth.uid()
));
drop policy if exists "necesidad propia editable" on public.necesidades;
create policy "necesidad propia editable" on public.necesidades for update to authenticated
using (exists (
    select 1 from public.fundaciones f
    where f.id = fundacion_id and f.usuario_id = auth.uid()
)) with check (exists (
    select 1 from public.fundaciones f
    where f.id = fundacion_id and f.usuario_id = auth.uid()
));

drop policy if exists "donaciones relacionadas visibles" on public.donaciones;
create policy "donaciones relacionadas visibles" on public.donaciones for select to authenticated
using (
    donante_id = auth.uid() or exists (
        select 1 from public.fundaciones f
        where f.id = fundacion_id and f.usuario_id = auth.uid()
    )
);
drop policy if exists "donacion propia insertable" on public.donaciones;
create policy "donacion propia insertable" on public.donaciones for insert to authenticated
with check (donante_id = auth.uid());
drop policy if exists "donacion gestionable por fundacion" on public.donaciones;
create policy "donacion gestionable por fundacion" on public.donaciones for update to authenticated
using (exists (
    select 1 from public.fundaciones f
    where f.id = fundacion_id and f.usuario_id = auth.uid()
));

drop policy if exists "fotos relacionadas visibles" on public.fotos_donacion;
create policy "fotos relacionadas visibles" on public.fotos_donacion for select to authenticated
using (exists (
    select 1 from public.donaciones d
    left join public.fundaciones f on f.id = d.fundacion_id
    where d.id = donacion_id and (d.donante_id = auth.uid() or f.usuario_id = auth.uid())
));
drop policy if exists "fotos propias insertables" on public.fotos_donacion;
create policy "fotos propias insertables" on public.fotos_donacion for insert to authenticated
with check (exists (
    select 1 from public.donaciones d
    where d.id = donacion_id and d.donante_id = auth.uid()
));

grant select, insert, update on public.perfiles to authenticated;
grant select, insert, update on public.fundaciones to authenticated;
grant select, insert, update on public.necesidades to authenticated;
grant select, insert, update on public.donaciones to authenticated;
grant select, insert on public.fotos_donacion to authenticated;
grant usage, select on all sequences in schema public to authenticated;

